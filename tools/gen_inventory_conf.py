#!/usr/bin/env python3
"""Generate the inventory KV Store collections and lookup definitions.

Usage: python3 -I tools/gen_inventory_conf.py

Rewrites the generated block at the end of package/default/collections.conf and
transforms.conf from shadowtrackr_lib.inventory_types. tests/test_inventory.py
fails when the files are out of date.
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "package", "bin"))

from shadowtrackr_lib.inventory_types import TRACKING_FIELDS, TYPES  # noqa: E402

MARKER = "# --- Inventory lookups, generated by tools/gen_inventory_conf.py; do not edit below ---\n"


def collections_block() -> str:
    out = [MARKER]
    for t in TYPES.values():
        out.append("\n[{}]\n".format(t.collection))
        out.append("field.st_first_synced = number\nfield.st_last_synced = number\nfield.st_present = number\n")
        out.append("field.organization_id = number\n")
    return "".join(out)


def transforms_block() -> str:
    out = [MARKER]
    for t in TYPES.values():
        out.append("\n[{}]\n".format(t.collection))
        out.append("external_type = kvstore\ncollection = {}\n".format(t.collection))
        if t.fields:
            fields = ("_key",) + t.fields + TRACKING_FIELDS
            out.append("fields_list = {}\n".format(", ".join(fields)))
    return "".join(out)


def render(path: str, block: str) -> str:
    with open(path, encoding="utf-8") as f:
        text = f.read()
    head = text.split(MARKER)[0].rstrip("\n") + "\n\n"
    return head + block


def main():
    for name, block in (("collections.conf", collections_block()), ("transforms.conf", transforms_block())):
        path = os.path.join(ROOT, "package", "default", name)
        text = render(path, block)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
